def rgba(v):
    v = v.lstrip('#')
    return int(v[2:4], 16), int(v[4:6], 16), int(v[6:8], 16), int(v[0:2], 16)


def luminance(rgb):
    def ch(c):
        c = c / 255
        return c / 12.92 if c <= 0.04045 else ((c + 0.055) / 1.055) ** 2.4
    r, g, b = rgb[:3]
    return 0.2126 * ch(r) + 0.7152 * ch(g) + 0.0722 * ch(b)


def contrast(fg, bg):
    a, b = luminance(rgba(fg)), luminance(rgba(bg))
    hi, lo = max(a, b), min(a, b)
    return (hi + 0.05) / (lo + 0.05)


def hue(v):
    import colorsys
    r, g, b, _ = rgba(v)
    h, l, s = colorsys.rgb_to_hls(r / 255, g / 255, b / 255)
    return h * 360, l, s


class DefinitionTest(unittest.TestCase):
    def test_the_definition_is_valid(self):
        self.assertEqual(themes.problems(D), [])

    def test_every_generated_copy_is_current(self):
        r = subprocess.run([sys.executable, str(ROOT / 'scripts' / 'rose-themes.py'), '--check'],
                           capture_output=True, text=True)
        self.assertEqual(r.returncode, 0, r.stderr)

    def test_the_copies_differ_only_in_their_package(self):
        bodies = set()
        for rel, pkg in themes.TARGETS.values():
            text = (ROOT / rel).read_text()
            self.assertIn('package %s;' % pkg, text)
            bodies.add(text.replace('package %s;' % pkg, 'package X;'))
        self.assertEqual(len(bodies), 1)

    def test_the_generated_java_is_pure(self):
        text = (ROOT / themes.TARGETS['app'][0]).read_text()
        self.assertNotRegex(text, r'import android\.')
        self.assertIn('GENERATED by scripts/rose-themes.py', text)

    def test_the_problems_catch_a_bad_theme(self):
        bad = json.loads(json.dumps(D))
        bad['themes'][1]['surfaces']['shade'].pop('error')
        bad['themes'][1]['wallpapers']['ids'].append('classic')
        bad['default'] = 'aurora'
        msgs = '\n'.join(themes.problems(bad))
        self.assertIn('glacier.shade: keys must be exactly', msgs)
        self.assertIn("wallpaper 'classic' belongs to both oxblood and glacier", msgs)
        self.assertIn('default must name a theme', msgs)


class GlacierAssetTest(unittest.TestCase):
    def test_the_field_is_the_illustrators_portrait_unchanged(self):
        wp = BY_ID['glacier']['wallpapers']
        data = (themes.THEMES / wp['asset']).read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(),
                         '98c7b166df806d0205396c5c2dd80fb470d96dbe2b619662cbd64a8d1099ba3e')
        self.assertEqual(data[:8], b'\x89PNG\r\n\x1a\n')
        w, h = struct.unpack('>II', data[16:24])
        self.assertEqual((w, h), (wp['width'], wp['height']))
        manifest = json.loads((themes.THEMES / 'glacier' / 'illustrator-manifest.json').read_text())
        portrait = next(f for f in manifest['files'] if f['name'] == 'glacier-portrait.png')
        self.assertEqual(portrait['sha256'], wp['sha256'])

    def test_every_package_carries_each_raster_theme_as_its_drawable(self):
        # Rose Agent and Launcher3 load a raster theme's wallpaper by its drawable name (RoseTheme.wallpaperDrawable).
        rasters = [t for t in D['themes'] if t['wallpapers']['kind'] == 'raster']
        self.assertTrue(rasters)
        for t in rasters:
            wp = t['wallpapers']
            source = (themes.THEMES / wp['asset']).read_bytes()
            for folder in themes.RASTER_DIRS:
                copy = ROOT / folder / (wp['drawable'] + '.png')
                self.assertTrue(copy.is_file(), copy)
                self.assertEqual(copy.read_bytes(), source, copy)
        for src in ('workspace/rose-agent/app/src/dev/pixel/voice/RoseThemeNow.java',
                    'os/overlays/packages/apps/Launcher3/quickstep/src/com/android/quickstep/fallback/RoseThemeSetting.java'):
            text = (ROOT / src).read_text()
            self.assertIn('RoseTheme.wallpaperDrawable(', text, src)
            self.assertNotIn('rose_glacier_field', text, src + ': no theme is named in loader code')

    def test_the_tokens_are_the_illustrators(self):
        tokens = json.loads((themes.THEMES / 'glacier' / 'glacier.tokens.json').read_text())['colors']
        # #0F1B27 is the prototype's keyboard top; the text table keeps today's white Rose text in Glacier.
        allowed = {('#FF' + v[1:]).upper() for v in tokens.values()} | {'#FF0F1B27', '#8C000000', '#FFFFFFFF', '#C7FFFFFF'}
        for surface, values in BY_ID['glacier']['surfaces'].items():
            for k, v in values.items():
                self.assertIn(v, allowed, 'glacier.%s.%s %s is not an approved token' % (surface, k, v))

    def test_the_reference_map_is_the_approved_prototype_copy(self):
        data = themes.REFERENCE.read_bytes()
        self.assertEqual(hashlib.sha256(data).hexdigest(), themes.REFERENCE_SHA256)
        # git blob 4654ef46 of prototypes/rose-hifi/glacier.py at 2ecceb97.
        blob = hashlib.sha1(b'blob %d\0' % len(data) + data).hexdigest()
        self.assertEqual(blob, '4654ef468705d3b34b9f33a57180a5004abe9aa6')


class OxbloodUnchangedTest(unittest.TestCase):
    """Oxblood's surface colours are exactly the colours the native renderers draw today."""

    def assertDrawn(self, path, values):
        text = (ROOT / path).read_text().lower()
        for v in values:
            self.assertIn('0x' + v[1:].lower(), text, '%s does not draw %s' % (path, v))

    def test_keyboard(self):
        self.assertDrawn('os/overlays/packages/apps/RoseKeyboard/src/dev/pixel/rose/keyboard/RoseKeyboardView.java',
                         BY_ID['oxblood']['surfaces']['keyboard'].values())

    def test_shade(self):
        # The outline was an inline 0x66F4EEEE (TEXT at 40%) before 1E; the shade now draws it from Shade.LINE, whose
        # Oxblood value must stay exactly that. Every other Oxblood value is still a declared shade constant.
        shade = dict(BY_ID['oxblood']['surfaces']['shade'])
        self.assertEqual(shade.pop('line'), '#66F4EEEE')
        self.assertDrawn(
            'os/overlays/frameworks/base/packages/SystemUI/src/com/android/systemui/roseshade/RoseShadeController.java',
            shade.values())

    def test_return_control(self):
        self.assertDrawn('workspace/rose-agent/app/src/dev/pixel/voice/ReturnControl.java',
                         BY_ID['oxblood']['surfaces']['returnControl'].values())

    def test_field(self):
        self.assertDrawn('workspace/rose-agent/app/src/dev/pixel/voice/OxbloodField.java',
                         BY_ID['oxblood']['surfaces']['field'].values())

    def test_wallpapers_are_the_curated_variants(self):
        src = (ROOT / 'workspace/rose-agent/app/src/dev/pixel/voice/OxbloodVariants.java').read_text()
        m = re.search(r'CLASSIC = "(\w+)", GARNET = "(\w+)", EMBER = "(\w+)", VELVET = "(\w+)", DUSK = "(\w+)"', src)
        self.assertEqual(list(m.groups()), BY_ID['oxblood']['wallpapers']['ids'])


class GlacierContrastTest(unittest.TestCase):
    """Opaque pairs the surfaces draw; text 4.5:1, accent ink on accent 4.5:1, control lines 3:1."""
    S = BY_ID['glacier']['surfaces']

    def test_every_glacier_surface_colour_is_opaque_except_the_scrim(self):
        for surface, values in self.S.items():
            for k, v in values.items():
                # The scrim, and Rose's secondary text (today's translucent white, unchanged), are translucent.
                if k != 'scrim' and (surface, k) != ('text', 'secondary'):
                    self.assertEqual(v[1:3], 'FF', 'glacier.%s.%s' % (surface, k))

    def test_shade(self):
        s = self.S['shade']
        for bg in ('panel', 'card', 'tile'):
            self.assertGreaterEqual(contrast(s['text'], s[bg]), 4.5, bg)
            self.assertGreaterEqual(contrast(s['text2'], s[bg]), 4.5, bg)
            self.assertGreaterEqual(contrast(s['error'], s[bg]), 4.5, bg)
            self.assertGreaterEqual(contrast(s['line'], s[bg]), 3.0, bg)
        self.assertGreaterEqual(contrast(s['accentInk'], s['accent']), 4.5)

    def test_keyboard(self):
        k = self.S['keyboard']
        for bg in ('keyTop', 'keyBottom', 'function', 'boardTop', 'boardBottom'):
            self.assertGreaterEqual(contrast(k['text'], k[bg]), 4.5, bg)
        self.assertGreaterEqual(contrast(k['actionInk'], k['actionTop']), 4.5)
        self.assertGreaterEqual(contrast(k['correction'], k['boardTop']), 3.0)

    def test_return_control(self):
        r = self.S['returnControl']
        for ink in ('ink', 'pendingInk', 'cancelInk'):
            self.assertGreaterEqual(contrast(r[ink], r['plateTop']), 4.5, ink)
            self.assertGreaterEqual(contrast(r[ink], r['pressed']), 4.5, ink)
        self.assertGreaterEqual(contrast(r['edge'], r['plateTop']), 3.0)

    def test_error_and_muted_stay_warm(self):
        for v in (self.S['shade']['error'], BY_ID['glacier']['derive']['destructive']):
            h, l, s = hue(v if len(v) == 9 else '#FF' + v[1:])
            self.assertTrue(h >= 300 or h <= 30, v)
            self.assertGreater(s, 0.35)

    def test_the_mapped_native_muted_inks_are_warm_and_readable(self):
        ref = themes.reference()
        # Oxblood's mic-muted ink, ring and the shade's error ink, through the prototype's warm rule.
        for v in ('#ff8c9a', '#ff5a6e', '#e07a88'):
            out = ref.warm_colors(v)
            h, l, s = hue('#FF' + out[1:])
            self.assertTrue(h >= 300 or h <= 30, (v, out))
        self.assertEqual(ref.warm_colors('#ff8c9a'), '#ffabac')


class GoldenTest(unittest.TestCase):
    def test_the_golden_values_are_the_prototype_map(self):
        ref = themes.reference()
        lines = [l for l in themes.GOLDEN.read_text().splitlines() if not l.startswith('#')]
        self.assertGreater(len(lines), 4000)
        for line in lines[::97]:
            c, m, w = (int(x, 16) for x in line.split())
            r, g, b = (c >> 16) & 255, (c >> 8) & 255, c & 255
            self.assertEqual(ref._map_rgb(r, g, b), ((m >> 16) & 255, (m >> 8) & 255, m & 255))


