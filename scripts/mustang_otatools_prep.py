#!/usr/bin/env python3
"""Build one independent Mustang otatools package, never an OTA or signing job.

The guard requires completed successful vendor evidence before START. Actual
generated bytes are rehashed under the canonical guest lock before Make.
The existing controller owns the VM lifecycle. All partial outputs remain.
"""
import argparse
import hashlib
import json
import os
from pathlib import Path
import pwd
import sys
import time

import mustang_controller as controller
import mustang_ephemeral as ephemeral
import mustang_hostdeps as deps
import mustang_lane
import mustang_ota
import mustang_preparation_inputs as inputs
import mustang_vendor_prep as vendor
import mustang_otatools_recovery as recovery

ROOT=Path(__file__).resolve().parents[1]
BINDING='os/build-only/mustang-otatools-preparation.json'
RECEIPT='otatools-preparation-receipt.json'
OUT='out_mustang_otatools_proof'
PATTERN='soong/.intermediates/build/make/tools/otatools_package/otatools-package/*/gen/otatools.zip'
TIMEOUT=9000
WORK_BYTES=128 << 30
RESERVE=300 << 30
PACKAGE_BYTES=4 << 30
FLAGS=vendor.FLAGS | {'otatools_only'}
SCRIPT=b'''#!/bin/bash
set -eo pipefail
test "$1" = out_mustang_otatools_proof
export ANDROID_QUIET_BUILD=true
export OUT_DIR="$1"
source build/envsetup.sh
lunch mustang-cur-user
/usr/bin/python3 - "$2" "$(get_build_var TARGET_PRODUCT)" "${TARGET_RELEASE:?lunch release missing}" "$(get_build_var TARGET_BUILD_VARIANT)" "$(get_build_var TARGET_DEVICE)" <<'PY'
import json,os,sys
identity=dict(zip(('TARGET_PRODUCT','TARGET_RELEASE','TARGET_BUILD_VARIANT','TARGET_DEVICE'),sys.argv[2:],strict=True))
with open(sys.argv[1],'x') as f:
    json.dump(identity,f);f.flush();os.fsync(f.fileno())
assert identity=={'TARGET_PRODUCT':'mustang','TARGET_RELEASE':'cur','TARGET_BUILD_VARIANT':'user','TARGET_DEVICE':'mustang'}, 'Mustang lunch identity differs'
PY
m -j24 otatools-package
'''


def binding(root=ROOT):
    cfg=json.loads((Path(root)/BINDING).read_text())
    expected={'schema':'roseos.mustang-otatools-preparation.v1','outDir':OUT,'product':'mustang-cur-user',
              'jobs':24,'goals':['otatools-package'],'timeoutSeconds':TIMEOUT,'workBytes':WORK_BYTES,
              'reserveBytes':RESERVE,'otaAdmitted':False,'signerPinsAdmitted':False}
    if any(type(cfg.get(k)) is not type(v) or cfg.get(k)!=v for k,v in expected.items()) \
            or not isinstance(cfg.get('vendorEvidence'),str):
        raise ValueError('otatools recipe or successful vendor evidence is unbound')
    record=inputs.evidence(cfg['vendorEvidence'],'roseos.mustang-vendor-evidence.v1',root)
    receipt=record['receipt']
    if receipt.get('schema')!='roseos.mustang-vendor-preparation-run.v1' or receipt.get('success') is not True \
            or receipt.get('phase')!='complete' or receipt.get('executionMode')!='pinned-typescript-source-loader' \
            or receipt.get('adevtoolTrackedWorktreeUnchanged') is not True \
            or receipt.get('source',{}).get('projectCount')!=1057 \
            or receipt.get('source',{}).get('check')!='project-heads-and-git-status' \
            or any(receipt.get(key) is not False for key in ('makeStarted','allocated','signingStarted','otaAdmitted')) \
            or len(receipt.get('commands',[]))!=3 \
            or any(c.get('processStarted') is not True or type(c.get('exitCode')) is not int \
                   or c.get('exitCode')!=0 for c in receipt['commands']) \
            or receipt['commands'][1].get('argv')!=['vendor/adevtool/bin/run','--help'] \
            or receipt['commands'][2].get('argv')!=['vendor/adevtool/bin/run','generate-all','-d','mustang']:
        raise ValueError('vendor evidence does not establish completed pinned-source generation')
    host,factory=vendor.binding(root)
    if receipt.get('hostDependencies',{}).get('receiptSha256')!=host['receiptSha256'] \
            or receipt.get('factoryInput',{}).get('receiptSha256')!=factory['receiptSha256']:
        raise ValueError('vendor generation belongs to different prepared inputs')
    selected=cfg.get('outputRecoveryEvidence')
    if selected is not None:
        if selected!=recovery.BINDING:raise ValueError('otatools recovery evidence path differs')
        _cfg,old,_observed=recovery.binding(root)
        if old['receipt']['vendorInput']['receiptSha256']!=record['receiptSha256'] \
                or old['receipt']['hostDependencies']['receiptSha256']!=host['receiptSha256']:
            raise ValueError('otatools recovery requires unchanged qualified inputs')
    return record,host


def guard(env,event,root=ROOT):
    lane=mustang_lane.validate(mustang_lane.configuration());run=controller.invocation(lane,env)
    selected=event.get('inputs') if isinstance(event,dict) else None
    disabled=lambda v:v is None or v is False or (type(v) is str and v=='false')
    if env.get('GITHUB_REPOSITORY_ID')!='1428996648' or not isinstance(selected,dict) \
            or set(selected)-FLAGS or not (selected.get('otatools_only') is True or selected.get('otatools_only')=='true') \
            or any(not disabled(selected.get(k)) for k in FLAGS-{'otatools_only'}):
        raise ValueError('otatools preparation requires its exclusive fresh manual scope')
    ephemeral.require_group5(json.loads((Path(root)/'os/build-only/mustang-runtime.json').read_text()))
    binding(root)
    return lane,run


def guest(env):
    lane,run=guard(env,deps.read_event(env))
    if env.get('GITHUB_JOB')!='otatools' or pwd.getpwuid(os.geteuid()).pw_name!='mustang-runner':
        raise ValueError('otatools requires the unprivileged dedicated guest job')
    cfg=json.loads((ROOT/'os/build-only/mustang-runtime.json').read_text())
    dedicated=mustang_ota.module('mustang_otatools_identity','mustang-dedicated.py')
    paths=dedicated.host_identity(lane,cfg['dataFilesystemUuid'],mount=cfg['dataMount'])
    source=Path(lane['sourceRoot'])
    for path in (source,paths['storageRoot']):
        if deps.plain_dir(path).st_dev!=deps.plain_dir(paths['home']).st_dev:
            raise ValueError('otatools leaves the dedicated data filesystem')
    env_clean=deps.child_env(paths['home']/'runner',paths['storageRoot']);deadline=time.monotonic()+60
    git=['/usr/bin/git','-c','core.fsmonitor=false','-c','core.hooksPath=/dev/null','-C',str(ROOT)]
    if deps.checked(git+['rev-parse','HEAD'],ROOT,env_clean,deadline)!=run['source'] \
            or deps.checked(git+['status','--porcelain'],ROOT,env_clean,deadline):
        raise ValueError('otatools checkout differs from captured clean source')
    return lane,dict(run=run,builder=lane['vm'],diskUuid=cfg['dataFilesystemUuid']),paths


def vendor_input(source,storage,record,identity,deadline):
    previous=inputs.receipt_on_disk(record,storage,'vendor',vendor.RECEIPT,identity)
    if previous.get('sourceRoot')!=str(source) or previous.get('phase')!='complete':
        raise ValueError('vendor source or completion differs')
    for key,relative in (('vendorTree','vendor/google_devices/mustang'),
                         ('nodeModules','vendor/adevtool/node_modules'),('adevtoolSource','vendor/adevtool/src')):
        if vendor.catalog(source,source/relative,deadline)!=previous.get(key):
            raise ValueError('generated vendor or pinned-source dependency bytes changed')
    for name,relative in (('binRun','bin/run'),('packageJson','package.json'),('yarnLock','yarn.lock')):
        if deps.fingerprint(source,source/'vendor/adevtool'/relative,deadline)!=previous.get('sourceLoader',{}).get(name):
            raise ValueError('pinned vendor source-loader bytes changed')
    if deps.fingerprint(source,source/'vendor/google_devices/mustang/mustang.mk',deadline)!=previous.get('productMakefile') \
            or os.path.lexists(source/'vendor/adevtool/lib'):
        raise ValueError('generated product or source-only runtime changed')
    return {'receiptSha256':record['receiptSha256'],'run':previous['identity']['run'],
            'generatedTreesRehashed':True,'sourceLoaderRehashed':True,'otaAdmitted':False}


def monitor(source,attempt,output,deadline,observations):
    used=deps.tree_bytes(output,deadline,allow_soong_ipc=True,max_entries=1_000_000)+deps.tree_bytes(attempt,deadline)
    space=os.statvfs(source);free=space.f_bavail*space.f_frsize
    observations['samples']=observations.get('samples',0)+1
    observations['peakWatchedBytes']=max(observations.get('peakWatchedBytes',0),used)
    observations['minimumAvailableBytes']=min(observations.get('minimumAvailableBytes',free),free)
    if used>WORK_BYTES or free<RESERVE or space.f_favail<=0:
        raise ValueError('otatools storage bound exceeded')
    if any(p.stat().st_size>deps.LOG_BYTES for p in attempt.glob('*.log')):
        raise ValueError('otatools log bound exceeded')


def collect(source,output,deadline):
    files=list(output.glob(PATTERN))
    if len(files)!=1:raise ValueError('otatools module output is absent or ambiguous')
    path=files[0];fd,info=deps.readers._open_regular(str(source),str(path))
    try:
        if not 0<info.st_size<=PACKAGE_BYTES:raise ValueError('otatools package size bound exceeded')
    finally:os.close(fd)
    result=deps.fingerprint(source,path,deadline)
    if not 0<result['sizeBytes']<=PACKAGE_BYTES:raise ValueError('otatools package size bound exceeded')
    return dict(result,path=str(path),relativePath=str(path.relative_to(output)),modulePattern=PATTERN)


def build(source,attempt,record,host,identity,root=ROOT):
    started=time.monotonic();deadline=started+TIMEOUT;output=source/OUT
    recovering=json.loads((Path(root)/BINDING).read_text()).get('outputRecoveryEvidence') is not None
    result={'schema':'roseos.mustang-otatools-preparation-run.v1','identity':identity,'success':False,
            'sourceRoot':str(source),'outDir':str(output),'product':'mustang-cur-user','goals':['otatools-package'],
            'jobs':24,'timeoutSeconds':TIMEOUT,'workBytes':WORK_BYTES,'reserveBytes':RESERVE,
            'makeStarted':False,'allocated':False,'signingStarted':False,'otaAdmitted':False,
            'signerPinsAdmitted':False,'partialsPreserved':True,'commands':[],'spaceObservations':{},
            'boundEnforcement':'sampled-process-group-stop','detachedDescendantsContained':False,'phase':'collision-check'}
    (attempt/'home').mkdir(mode=0o700);(attempt/'tmp').mkdir(mode=0o700)
    env=deps.child_env(attempt/'home',attempt/'tmp')
    env['BUILD_NUMBER']='mustang-otatools-proof-'+identity['run']['runId']
    check=lambda:monitor(source,attempt,output,deadline,result['spaceObservations'])
    try:
        if os.path.lexists(output) and not recovering:raise ValueError('otatools output exists; preserve and reconcile it')
        check();space=os.statvfs(source)
        if space.f_bavail*space.f_frsize<RESERVE+WORK_BYTES:raise ValueError('otatools reserve headroom is insufficient')
        result['phase']='pinned-source-check';result['source']=deps.source_check(source,env,deadline,root)
        result['phase']='vendor-input-rehash';result['vendorInput']=vendor_input(source,attempt.parent,record,identity,deadline)
        result['phase']='host-dependency-rehash'
        result['hostDependencies']=inputs.host_dependencies(source,attempt.parent,host,identity,deadline=deadline,root=root)
        if recovering:
            result['phase']='retain-failed-output'
            result['outputRetention']=recovery.retain(source,attempt.parent,identity,root=root)
        if os.path.lexists(output):raise ValueError('otatools output still exists after retention')
        script=attempt/'build-otatools.sh';script.write_bytes(SCRIPT)
        result['buildScript']=deps.fingerprint(attempt,script,deadline)
        command=['/bin/bash',str(script),OUT,str(attempt/'lunch-identity.json')]
        outcome={'argv':command,'processStarted':False,'exitCode':None};result['commands'].append(outcome)
        result['phase']='mustang-otatools-make'
        try:deps.supervise(command,source,env,attempt/'make.log',deadline,check,outcome=outcome,
                           failure_message='Mustang otatools Make failed')
        finally:result['makeStarted']=None if outcome['processStarted'] else False
        result['actualLunchIdentity']=json.loads(deps.readers.read_regular(str(attempt),str(attempt/'lunch-identity.json'),65536))
        if result['actualLunchIdentity']!={'TARGET_PRODUCT':'mustang','TARGET_RELEASE':'cur','TARGET_BUILD_VARIANT':'user','TARGET_DEVICE':'mustang'}:
            raise ValueError('actual Mustang lunch identity differs')
        result['phase']='otatools-package-hash';result['package']=collect(source,output,deadline)
        result['phase']='input-readback';result['vendorReadback']=vendor_input(source,attempt.parent,record,identity,deadline)
        result['sourceReadback']=deps.source_check(source,env,deadline,root)
        check();result.update(success=True,makeStarted=True,makeExitCode=0,phase='complete')
    except BaseException as error:
        result['failureType']=type(error).__name__
        result['failureCode']=str(error) if isinstance(error,ValueError) else 'otatools-preparation-operation-failed'
        raise
    finally:
        result['elapsedSeconds']=round(time.monotonic()-started,3);deps.receipt(attempt/RECEIPT,result)
    return result


def execute(env):
    lane,identity,paths=guest(env)
    with deps.lock(Path(lane['lockPath'])):
        attempt=paths['storageRoot']/('mustang-otatools-'+identity['run']['runId']+'-'+identity['run']['runAttempt'])
        attempt.mkdir(mode=0o750);deps.plain_dir(attempt)
        record,host=binding();return build(Path(lane['sourceRoot']),attempt,record,host,identity)


def report(env,destination):
    result,_raw=load_report(env)
    deps.receipt(destination,result)


def load_report(env):
    _lane,identity,paths=guest(env)
    path=paths['storageRoot']/('mustang-otatools-'+identity['run']['runId']+'-'+identity['run']['runAttempt'])/RECEIPT
    raw=deps.readers.read_regular(str(paths['storageRoot']),str(path),1 << 20);result=json.loads(raw)
    if result.get('schema')!='roseos.mustang-otatools-preparation-run.v1' or result.get('identity')!=identity:
        raise ValueError('otatools report belongs to another run or builder')
    return result,raw


def export_package(env,destination):
    result,raw=load_report(env)
    if result.get('success') is not True or result.get('phase')!='complete' or result.get('makeExitCode')!=0:
        raise ValueError('only a successful otatools package can be exported')
    temporary=Path(env['RUNNER_TEMP']);deps.plain_dir(temporary)
    if temporary!=ephemeral.RUNNER_ROOT/'_work/_temp' \
            or deps.plain_dir(temporary).st_dev!=deps.plain_dir(Path(result['sourceRoot'])).st_dev:
        raise ValueError('otatools export must stay on the dedicated runner data filesystem')
    if destination!=temporary/'mustang-otatools-export':raise ValueError('otatools export path differs')
    package=result['package'];source=Path(result['sourceRoot']);path=Path(package['path'])
    deadline=time.monotonic()+900
    if collect(source,source/OUT,deadline)!=package:raise ValueError('otatools package changed before export')
    destination.mkdir(mode=0o700)
    fd,info=deps.readers._open_regular(str(source),str(path));digest=hashlib.sha256();size=0
    try:
        if info.st_size!=package['sizeBytes']:raise ValueError('otatools source size changed')
        with os.fdopen(fd,'rb') as incoming,open(destination/'otatools.zip','xb') as outgoing:
            fd=None
            while block:=incoming.read(1 << 20):
                size+=len(block)
                if size>package['sizeBytes'] or time.monotonic()>=deadline:
                    raise ValueError('otatools export bound exceeded')
                space=os.statvfs(source)
                if space.f_bavail*space.f_frsize<RESERVE:raise ValueError('otatools export reserve exhausted')
                digest.update(block);outgoing.write(block)
            outgoing.flush();os.fsync(outgoing.fileno())
    finally:
        if fd is not None:os.close(fd)
    if size!=package['sizeBytes'] or digest.hexdigest()!=package['sha256']:
        raise ValueError('otatools export bytes differ')
    with open(destination/RECEIPT,'xb') as handle:
        handle.write(raw);handle.flush();os.fsync(handle.fileno())


def verify_export(directory,env,destination):
    """Hosted same-run byte check only: no key, OIDC, native tool execution or pins."""
    lane=mustang_lane.validate(mustang_lane.configuration());run=controller.invocation(lane,env)
    if env.get('GITHUB_JOB')!='otatools-verify':raise ValueError('otatools verification requires its independent hosted job')
    raw=deps.readers.read_regular(str(directory),str(directory/RECEIPT),1 << 20);native=json.loads(raw)
    cfg=json.loads((ROOT/'os/build-only/mustang-runtime.json').read_text())
    if native.get('schema')!='roseos.mustang-otatools-preparation-run.v1' \
            or native.get('identity')!=dict(run=run,builder=lane['vm'],diskUuid=cfg['dataFilesystemUuid']) \
            or native.get('success') is not True or native.get('phase')!='complete' \
            or type(native.get('makeExitCode')) is not int or native.get('makeExitCode')!=0 \
            or native.get('product')!='mustang-cur-user' or native.get('goals')!=['otatools-package'] \
            or native.get('jobs')!=24 or native.get('outDir')!=str(Path(lane['sourceRoot'])/OUT) \
            or native.get('sourceRoot')!=lane['sourceRoot'] \
            or any(native.get(k) is not False for k in ('allocated','signingStarted','otaAdmitted','signerPinsAdmitted')):
        raise ValueError('native otatools receipt belongs to another run, source or scope')
    package=native.get('package',{})
    relative=Path(package.get('relativePath',''))
    if relative.is_absolute() or '..' in relative.parts or not relative.match(PATTERN) \
            or package.get('modulePattern')!=PATTERN or package.get('path')!=str(Path(lane['sourceRoot'])/OUT/relative):
        raise ValueError('native otatools module path differs')
    fd,info=deps.readers._open_regular(str(directory),str(directory/'otatools.zip'))
    try:
        if not 0<info.st_size<=PACKAGE_BYTES or info.st_size!=package.get('sizeBytes'):
            raise ValueError('downloaded otatools size differs')
    finally:os.close(fd)
    observed=deps.fingerprint(directory,directory/'otatools.zip',time.monotonic()+900)
    if any(observed[k]!=package.get(k) for k in ('sha256','sizeBytes')):
        raise ValueError('downloaded otatools bytes differ')
    result={'schema':'roseos.mustang-otatools-independent-readback.v1','run':run,
            'nativeReceiptSha256':hashlib.sha256(raw).hexdigest(),'packageSha256':observed['sha256'],
            'packageBytes':observed['sizeBytes'],'byteReadbackMatches':True,'packageExecuted':False,
            'otaAdmitted':False,'signerPinsAdmitted':False}
    deps.receipt(destination,result)
    return result


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('action',choices=('plan','run','report','export','verify-export'),nargs='?',default='plan')
    parser.add_argument('--execute',action='store_true');parser.add_argument('--out',type=Path)
    parser.add_argument('--dir',type=Path)
    args=parser.parse_args()
    if args.action=='plan' or (args.action=='run' and not args.execute):
        print(json.dumps({'execute':False,'scope':'Mustang-otatools-only','binding':BINDING,'outDir':OUT,
                          'product':'mustang-cur-user','jobs':24,'goals':['otatools-package']}));return 4
    if args.action=='verify-export':
        if args.out is None or args.dir is None:raise ValueError('otatools verification input/output is required')
        verify_export(args.dir,os.environ,args.out)
    elif args.action in ('report','export'):
        if args.out is None:raise ValueError('otatools report output is required')
        if args.action=='export':export_package(os.environ,args.out)
        else:report(os.environ,args.out)
    else:execute(os.environ)
    return 0


if __name__=='__main__':
    try:sys.exit(main())
    except (ValueError,OSError) as error:
        print(json.dumps({'success':False,'failure':str(error) if type(error) is ValueError else type(error).__name__,
                          'authenticatedStop':False}));sys.exit(4)
