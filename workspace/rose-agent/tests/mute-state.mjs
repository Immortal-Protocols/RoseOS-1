import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../app/assets/index.html',import.meta.url),'utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)[1].replace('check();poll();refreshApps();','');
const nodes=new Map();
const context=vm.createContext({window:{},localStorage:{getItem(){return null},setItem(){}},console,Map,Promise,JSON,Error,setTimeout:()=>1,setInterval:()=>1,clearInterval:()=>{},clearTimeout:()=>{},Audio:class{},Native:{audio(){},audioPrepared(){return true},endpoint(){return 'https://example.invalid';},request(){}},document:{getElementById(id){if(!nodes.has(id))nodes.set(id,{textContent:'',classList:{remove(){},add(){}}});return nodes.get(id);}}});
vm.runInContext(source,context);
vm.runInContext(`var track={enabled:true,readyState:'live',stop(){this.readyState='ended'}}; mic={getAudioTracks:()=>[track],getTracks:()=>[track]};ready=true;ended=false;peer={connectionState:'connected',close(){}};channel={readyState:'open',close(){}};toggleMute();`,context);
assert.equal(vm.runInContext('track.enabled',context),false);
assert.equal(nodes.get('mute').textContent,'Unmute');
vm.runInContext('toggleMute()',context);
assert.equal(vm.runInContext('track.enabled',context),true);
assert.equal(nodes.get('mute').textContent,'Mute');
vm.runInContext('toggleMute();cleanup()',context);
assert.equal(vm.runInContext('muted',context),false);
assert.equal(nodes.get('mute').textContent,'Mute');
vm.runInContext(`track.readyState='ended';mic={getAudioTracks:()=>[track],getTracks:()=>[track]};ready=true;ended=false;peer={connectionState:'connected',close(){}};channel={readyState:'open',close(){}};toggleMute();`,context);
assert.equal(nodes.get('status').textContent,'Voice unavailable. Tap Talk to reconnect.');
assert.equal(nodes.get('mute').disabled,true);
assert.equal(nodes.get('talk').disabled,false);
console.log('PASS: mute/unmute tracks, cleanup reset, and ended microphone recovery');
// An explicit End must cancel both a pending capture and automatic prewarming.
vm.runInContext(`var finishCapture;var warmSchedules=0;
setTimeout=()=>{warmSchedules++;return 1};
api=()=>Promise.resolve({});relay=()=>{};
Native.audioRoute=()=>'';Native.timing=()=>{};
performance={now:()=>0};
navigator={mediaDevices:{getUserMedia:()=>new Promise(r=>finishCapture=r)}};
ready=false;starting=false;peer=null;channel=null;mic=null;
var pendingStart=start(false);`,context);
await new Promise(resolve=>setImmediate(resolve));
vm.runInContext(`endConversation();
var lateTrack={stop(){this.stopped=true}};
finishCapture({getTracks:()=>[lateTrack]});`,context);
await vm.runInContext('pendingStart',context);
await new Promise(resolve=>setImmediate(resolve));
assert.equal(vm.runInContext('lateTrack.stopped',context),true);
assert.equal(vm.runInContext('mic',context),null);
assert.equal(vm.runInContext('starting',context),false);
assert.equal(vm.runInContext('explicitlyStopped',context),true);
// Start watchdog plus a microphone-free preparation timer.
assert.equal(vm.runInContext('warmSchedules',context),1);
assert.equal(vm.runInContext('audio.muted',context),true);
await vm.runInContext('activate()',context);
assert.equal(vm.runInContext('mic',context),null);
console.log('PASS: End discards delayed capture; no preparation is scheduled after explicit End');
vm.runInContext(`track.readyState='live';track.enabled=true;mic={getAudioTracks:()=>[track],getTracks:()=>[track]};ready=true;parked=false;muted=false;ended=false;peer={connectionState:'connected'};channel={readyState:'open'};window.glassesTap();`,context);
assert.equal(vm.runInContext('track.enabled',context),false);
assert.equal(vm.runInContext('muted',context),true);
vm.runInContext('performance.now=()=>500;window.glassesTap()',context);
assert.equal(vm.runInContext('track.enabled',context),true);
assert.equal(vm.runInContext('muted',context),false);
vm.runInContext('window.startFromGlasses()',context);
assert.equal(vm.runInContext('track.enabled',context),true);
console.log('PASS: glasses tap toggles microphone; automatic start does not mute active voice');
vm.runInContext(`var otherTrack={kind:'audio',enabled:true,readyState:'live'};peer.getSenders=()=>[{track:otherTrack}];toggleMute();`,context);
assert.equal(vm.runInContext('otherTrack.enabled',context),false);
vm.runInContext('window.autoStartFromGlasses()',context);
assert.equal(vm.runInContext('muted',context),true);
assert.equal(vm.runInContext('track.enabled',context),false);
vm.runInContext('otherTrack.enabled=true;enforceMute()',context);
assert.equal(vm.runInContext('otherTrack.enabled',context),false);
vm.runInContext('toggleMute()',context);
assert.equal(vm.runInContext('otherTrack.enabled',context),true);
console.log('PASS: all outgoing tracks muted, reconnect cannot unmute, muted track replacement guarded');
vm.runInContext(`var activations=0;var coldStarts=0;activate=()=>{activations++};start=()=>{coldStarts++};ready=true;parked=true;explicitlyStopped=true;window.autoStartFromGlasses();`,context);

assert.equal(vm.runInContext('activations',context),1);
assert.equal(vm.runInContext('explicitlyStopped',context),false);
vm.runInContext('ready=false;starting=true;wantActivate=false;window.autoStartFromGlasses()',context);
assert.equal(vm.runInContext('wantActivate',context),true);
vm.runInContext('starting=false;window.autoStartFromGlasses()',context);
assert.equal(vm.runInContext('coldStarts',context),1);
console.log('PASS: reconnect activates prepared voice, queues starting voice, starts cold voice');
