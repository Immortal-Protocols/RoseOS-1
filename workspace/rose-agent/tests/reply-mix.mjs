import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../app/assets/index.html',import.meta.url),'utf8');
const code=source.slice(source.indexOf('class ReplyActivityTracker'),source.indexOf('let replyMixTimer'));
const c=vm.createContext({});vm.runInContext(code+';globalThis.Tracker=ReplyActivityTracker;',c);
const t=new c.Tracker();
assert.equal(t.sample(0,0,0),false);
assert.equal(t.sample(.01,.15,150),true);
assert.equal(t.sample(.01,.30,600),true);
assert.equal(t.sample(.01,.9,900),false);
assert.equal(t.sample(0,0,1000),false);
assert.equal(t.sample(NaN,NaN,1050),false);
assert.equal(t.sample(.001,.15,1100),true);
assert.ok(source.includes('function cleanup(){stopReplyMix();'));
console.log('PASS reply audio activity, silence hold, silence release, counter reset, invalid stats, cleanup');
