import assert from 'node:assert/strict';
import {PhoneCommands} from '../server/phone.mjs';
let now=1000;const p=new PhoneCommands(()=>now);
assert.throws(()=>p.create({action:'shell'}));
assert.throws(()=>p.create({action:'open_app',packageName:'x; reboot'}));
const a=p.create({action:'list_apps'});
assert.equal(p.pending().length,1);
p.complete(a.id,{status:'ok',apps:[]});
assert.equal(p.pending().length,0);
p.complete(a.id,{status:'error'});
assert.equal(p.get(a.id).result.status,'ok'); // replay cannot change result
const b=p.create({action:'open_app',packageName:'dev.pixel.calculator'});
now+=20001;
assert.equal(p.pending().length,0);
assert.equal(p.get(b.id).status,'expired');
p.complete(b.id,{status:'launch_requested'});
assert.equal(p.get(b.id).status,'expired');
console.log('Phone command validation, replay and expiry passed');
const visualId='12345678-1234-1234-1234-123456789abc';
const visual=p.create({action:'screen_gesture',screenshotId:visualId,points:[100,200]});
assert.equal(visual.screenshotId,visualId);
assert.deepEqual(visual.points,[100,200]);
assert.throws(()=>p.create({action:'screen_gesture',screenshotId:visualId,points:[100,200],nodeId:0}));
assert.throws(()=>p.create({action:'screen_gesture',screenshotId:visualId,points:[100,200],snapshotId:visualId}));
assert.throws(()=>p.create({action:'screen_gesture',screenshotId:visualId,points:[100,-1]}));
assert.throws(()=>p.create({action:'screen_gesture',points:[100,200]}));
assert.throws(()=>p.create({action:'screen_gesture',screenshotId:visualId,points:[100,200,300]}));
assert.throws(()=>p.create({action:'screen_gesture',screenshotId:visualId,points:[100,200,300,400],durationMs:10}));
assert.equal(p.create({action:'screenshot',visualOnly:true}).visualOnly,true);
console.log('Screenshot-only gestures reject accessibility targets and invalid geometry');
const snap='01234567-89ab-cdef-0123-456789abcdef';
assert.throws(()=>p.create({action:'tap',nodeId:1}));
assert.throws(()=>p.create({action:'tap',snapshotId:snap,nodeId:-1}));
assert.throws(()=>p.create({action:'tap',snapshotId:snap,nodeId:1.5}));
assert.throws(()=>p.create({action:'scroll',snapshotId:snap,nodeId:1,direction:'left'}));
assert.throws(()=>p.create({action:'set_text',snapshotId:snap,nodeId:1,text:'a'.repeat(4001)}));
const click=p.create({action:'tap',snapshotId:snap,nodeId:2});
assert.equal(click.snapshotId,snap);assert.equal(click.nodeId,2);
for(const action of ['screenshot','diagnostics','control_status','setup_ui_control','inspect_ui','home','back'])assert.equal(p.create({action}).action,action);
const fill=p.create({action:'set_text',snapshotId:snap,nodeId:4,text:'literal $HOME; `text`'});assert.equal(fill.text,'literal $HOME; `text`');
console.log('UI action validation and argument preservation passed');
assert.throws(()=>p.create({action:'tap_label',snapshotId:snap,label:''}));
assert.throws(()=>p.create({action:'tap_label',snapshotId:snap,label:'a'.repeat(201)}));
const semantic=p.create({action:'tap_label',snapshotId:snap,label:'3'});
assert.equal(semantic.label,'3');assert.equal(semantic.nodeId,undefined);
console.log('Semantic target schema passed');
assert.throws(()=>p.create({action:'ime_enter',nodeId:1}));
assert.throws(()=>p.create({action:'ime_enter',snapshotId:snap,nodeId:-1}));
const enter=p.create({action:'ime_enter',snapshotId:snap,nodeId:4});
assert.equal(enter.action,'ime_enter');assert.equal(enter.nodeId,4);
console.log('Keyboard action requires a fresh snapshot and valid target');

assert.throws(()=>p.create({action:'touch_label',label:'Example'}));
assert.throws(()=>p.create({action:'touch_label',snapshotId:snap,label:''}));
const touch=p.create({action:'touch_label',snapshotId:snap,label:'Example'});
assert.equal(touch.action,'touch_label');assert.equal(touch.label,'Example');
console.log('Touch fallback requires fresh snapshot and exact label');
const swipe=p.create({action:'swipe',snapshotId:snap,nodeId:13,direction:'left',bounds:[10,900,1000,1030]});
assert.deepEqual(swipe.bounds,[10,900,1000,1030]);
for(const patch of [{direction:'down'},{bounds:[0,0,1,1]},{bounds:[0,0,NaN,500]},{snapshotId:''},{nodeId:-1}])assert.throws(()=>p.create({...swipe,...patch}));
console.log('Horizontal swipes require a fresh target, direction and valid visible region');

const card=p.create({action:'touch_label',snapshotId:snap,label:'Submit',nodeId:29});
assert.equal(card.nodeId,29);assert.equal(card.label,'Submit');
for(const nodeId of [-1,300,1.2,null])assert.throws(()=>p.create({action:'touch_label',snapshotId:snap,label:'Submit',nodeId}));
console.log('Explicit visual label disambiguation validates the node ID');

const drag=p.create({action:'drag',snapshotId:snap,nodeId:8,points:[10,20,100,200],durationMs:600});
assert.deepEqual(drag.points,[10,20,100,200]);
for(const patch of [{points:[1,2,1,2]},{points:[1,2,3]},{points:[0,0,Infinity,100]},{durationMs:199},{durationMs:2001},{nodeId:-1}])assert.throws(()=>p.create({...drag,...patch}));
console.log('Precise drag endpoints and duration validation passed');
const point=p.create({action:'touch_point',snapshotId:snap,nodeId:2,x:540,y:700});
assert.equal(point.x,540);assert.equal(point.y,700);
for(const patch of [{x:-1},{y:NaN},{x:1.5},{x:20001},{snapshotId:''},{nodeId:300}])assert.throws(()=>p.create({...point,...patch}));
console.log('Visual point taps require a fresh surface and valid display coordinates');

const santaAna={id:'santa-ana-test',kind:'wind',title:'Santa Ana winds',subtitle:'NWS outlook',source:'NWS Los Angeles/Oxnard',updatedAt:'2026-10-13T19:57:00-07:00',wind:{origin:'Great Basin high pressure',barrier:'Over the mountains',destination:'Down to valleys and coast',direction:'Northeast / offshore',effect:'Descending air compresses, warming and drying.',peak:'Strongest Thursday–Friday',caution:'Regional fire-weather and heat alerts; check local notices.'}};
const windCommand=p.create({action:'visualization_set',visual:santaAna});
assert.equal(windCommand.visual.kind,'wind');assert.equal(windCommand.visual.wind.peak,santaAna.wind.peak);
for(const patch of [{kind:'html'},{wind:{...santaAna.wind,origin:'x'.repeat(51)}},{wind:{...santaAna.wind,effect:'bad\u0000text'}},{wind:{...santaAna.wind,peak:undefined}}])assert.throws(()=>p.create({action:'visualization_set',visual:{...santaAna,...patch}}));
console.log('Wind visual schema accepts bounded airflow cards and rejects malformed values');

const timer=p.create({action:'clock_timer_start',seconds:300,label:'Pasta'});
assert.equal(timer.seconds,300);assert.equal(timer.label,'Pasta');
for(const seconds of [0,-1,86401,1.5,'300',NaN])assert.throws(()=>p.create({action:'clock_timer_start',seconds}));
assert.throws(()=>p.create({action:'clock_timer_start',seconds:300,label:'x'.repeat(101)}));
p.complete(timer.id,{status:'verified_timer_started',timerId:7});
p.complete(timer.id,{status:'error'});assert.equal(p.get(timer.id).result.timerId,7);
console.log('Timer bounds, label preservation, and completed-command replay passed');

assert.equal(p.create({action:"tap_label",snapshotId:snap,label:"Last visible control",nodeId:299}).nodeId,299);
