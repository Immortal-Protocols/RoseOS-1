import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const html=fs.readFileSync(new URL('../app/assets/index.html',import.meta.url),'utf8');
const source=html.match(/<script>([\s\S]*?)<\/script>/)[1].replace('check();poll();refreshApps();','');
const nodes=new Map();
const context=vm.createContext({window:{},localStorage:{getItem(){return null},setItem(){}},console,Map,Promise,JSON,Error,setTimeout:()=>1,setInterval:()=>1,clearInterval(){},clearTimeout(){},Audio:class{},Native:{audio(){},endpoint(){return 'https://example.invalid';},request(){},audioRoute(){return ''}},document:{getElementById(id){if(!nodes.has(id))nodes.set(id,{textContent:'',classList:{remove(){},add(){}}});return nodes.get(id);}}});
vm.runInContext(source,context);
vm.runInContext(`relay=()=>{};var track={enabled:true,readyState:'live'};mic={getAudioTracks:()=>[track]};ready=true;parked=false;ended=false;muted=false;peer={connectionState:'connected'};channel={readyState:'open'};window.setTrayMuted(true);window.setTrayMuted(true);`,context);
assert.equal(vm.runInContext('track.enabled',context),false);
assert.equal(vm.runInContext('muted',context),true);
vm.runInContext('window.setTrayMuted(false);window.setTrayMuted(false)',context);
assert.equal(vm.runInContext('track.enabled',context),true);
assert.equal(vm.runInContext('muted',context),false);
vm.runInContext('parked=true;window.setTrayMuted(true)',context);
assert.equal(vm.runInContext('muted',context),false);
vm.runInContext('ready=false;parked=false;window.setTrayMuted(true)',context);
assert.equal(vm.runInContext('muted',context),false);
console.log('PASS: explicit tray mute/unmute is idempotent and cannot activate parked/ended voice');
