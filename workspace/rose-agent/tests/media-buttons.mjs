import vm from 'node:vm';
import fs from 'node:fs';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../app/assets/index.html',import.meta.url),'utf8').match(/<script>([\s\S]*?)<\/script>/)[1].replace('check();poll();refreshApps();','');
const nodes=new Map(),handlers=new Map();let now=0,context;
context=vm.createContext({window:{},navigator:{mediaSession:{setActionHandler:(name,fn)=>handlers.set(name,fn)}},performance:{now:()=>now},localStorage:{getItem(){return null},setItem(){}},console,setTimeout:()=>1,setInterval:()=>1,clearTimeout(){},clearInterval(){},Audio:class{pause(){}},Native:{audio(){},endpoint:()=>'',request(){},audioRoute:()=>'',glassesMediaAction(action){vm.runInContext(action==='next'?'endConversation()':'window.glassesTap()',context)}},document:{getElementById(id){if(!nodes.has(id))nodes.set(id,{textContent:'',classList:{add(){},remove(){}}});return nodes.get(id)}}});
vm.runInContext(source,context);
vm.runInContext(`relay=()=>{};var t={kind:'audio',enabled:true,readyState:'live'};mic={getAudioTracks:()=>[t]};peer={connectionState:'connected',getSenders:()=>[{track:t}]};channel={readyState:'open'};ready=true;parked=false;muted=false;`,context);
handlers.get('pause')();
assert.equal(vm.runInContext('muted',context),true);
vm.runInContext('window.glassesTap()',context);
assert.equal(vm.runInContext('muted',context),true,'duplicate native delivery must not undo mute');
now=500;handlers.get('play')();
assert.equal(vm.runInContext('muted',context),false);
assert.equal(vm.runInContext('t.enabled',context),true);
console.log('PASS: browser media controls toggle mic; duplicate native event cannot double-toggle');

vm.runInContext(`t.stop=()=>{t.readyState='ended'};mic.getTracks=()=>[t];peer.close=()=>{};channel.close=()=>{};api=()=>Promise.resolve({});`,context);
handlers.get('nexttrack')();
assert.equal(vm.runInContext('ended',context),true);
assert.equal(vm.runInContext('explicitlyStopped',context),true);
assert.equal(vm.runInContext('t.readyState',context),'ended');
vm.runInContext(`var starts=0;start=()=>{starts++};`,context);
assert.equal(vm.runInContext('starts',context),0);
now=1000;handlers.get('play')();
assert.equal(vm.runInContext('starts',context),1);
assert.equal(vm.runInContext('explicitlyStopped',context),false);
console.log('PASS: next-track ends capture and stays off; deliberate single tap restarts');
