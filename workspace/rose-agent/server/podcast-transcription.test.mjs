import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import {podcastTranscription,chunkStarts} from './podcast-transcription.mjs';
const dir=fs.mkdtempSync(path.join(os.tmpdir(),'podcast-test-'));
const pause=()=>new Promise(r=>setTimeout(r,5));
let clock=1000,calls=0,release;
const service=podcastTranscription(dir,null,{now:()=>clock,extract:async()=>Buffer.from('audio'),transcribe:async()=>{calls++;await new Promise(r=>release=r);return {text:'Cached test passage',words:[{word:'Cached',start:0.2,end:0.6},{word:'test',start:0.6,end:0.9},{word:'passage',start:0.9,end:1.2}]};}});
const data={audioUrl:'https://example.com/podcast.mp3',positionMs:300000,durationMs:600000,playing:true,foreground:true};
assert.deepEqual(chunkStarts(0,90000).sort((a,b)=>a-b),[0,30000,60000]);
service.sync({...data,playing:false});await pause();assert.equal(calls,0);
service.sync(data);await pause();assert.equal(calls,1);
service.sync({...data,playing:false});release();await pause();assert.equal(calls,1,'pause prevents the next paid chunk');assert.equal(service.sync({...data,playing:false}).segments.length,1);
const cached=service.sync({...data,playing:false}).segments[0];
assert.equal(cached.words[0].startMs,cached.startMs+200);
assert.equal(cached.words[2].endMs,cached.startMs+1200);
assert.equal(cached.timing,'word-aligned');
service.sync(data);await pause();assert.equal(calls,2);
service.sync({active:false});release();await pause();assert.equal(calls,2,'leaving stops new calls');
const restored=podcastTranscription(dir,null,{extract:async()=>{throw Error('should not run');}});
assert.equal(restored.sync({...data,lookupOnly:true}).segments.length,2,'cache persists across restarts');
assert.equal(calls,2);
fs.rmSync(dir,{recursive:true,force:true});
console.log('PASS: bounded windows, paused startup, stop after in-flight request, leaving, persistent cache reuse');
